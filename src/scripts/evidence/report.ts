import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import type { ScenarioRecord } from './harness';

function json(value: unknown): string {
  return value === undefined ? '(none)' : JSON.stringify(value, null, 2);
}

function section(r: ScenarioRecord): string {
  return [
    `## ${r.id}. ${r.name} - ${r.pass ? 'PASS' : 'FAIL'}`,
    '',
    `- Request: \`${r.method} ${r.path}\``,
    `- Expected: ${r.expected}`,
    `- Status: ${r.status ?? 'n/a'}`,
    '',
    'Request body:',
    '```json',
    json(r.requestBody),
    '```',
    '',
    'Response body:',
    '```json',
    json(r.responseBody),
    '```',
    '',
  ].join('\n');
}

export async function writeReport(records: ScenarioRecord[]): Promise<string> {
  const failed = records.filter((r) => !r.pass).length;
  const table = [
    '| # | Scenario | Expected | Status | Result |',
    '|---|----------|----------|--------|--------|',
    ...records.map(
      (r) =>
        `| ${r.id} | ${r.name} | ${r.expected} | ${r.status ?? 'n/a'} | ${r.pass ? 'PASS' : 'FAIL'} |`,
    ),
  ].join('\n');
  const content = [
    '# Evidence: Dynamic Pricing & Promotion Engine - Delivery 1',
    '',
    'Generated by `npm run evidence` against an in-memory MongoDB replica set.',
    '',
    `Overall: ${failed === 0 ? 'ALL PASS' : `${failed} FAILED`} (${records.length} scenarios)`,
    '',
    table,
    '',
    ...records.map(section),
  ].join('\n');
  const file = resolve(__dirname, '../../../docs/evidence/EVIDENCE.md');
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content);
  return file;
}
